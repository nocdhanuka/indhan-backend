public class SelectedNumbers {

    String number;
    long datetie;
    String status;

    public String getNumber() {
        return number;
    }

    public void setNumber(String number) {
        this.number = number;
    }

    public long getDatetie() {
        return datetie;
    }

    public void setDatetie(long datetie) {
        this.datetie = datetie;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

}
